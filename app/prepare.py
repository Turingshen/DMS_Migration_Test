def is_auto_generated_id(doc_number):
    """
    Check if a document number is auto-generated by SAP.
    Auto-generated IDs are 25 characters long and numeric after removing leading zeros.
    
    Args:
        doc_number: Document number to check
        
    Returns:
        bool: True if auto-generated, False if manual ID
    """
    if not doc_number:
        return False
    
    doc_str = str(doc_number).strip()
    
    # Check length requirement
    if len(doc_str) != 25:
        return False
    
    # Try to convert to int after removing leading zeros
    try:
        int(doc_str.lstrip('0') or '0')
        return True
    except (ValueError, TypeError):
        return False


def load_translations():
    """Load active migration rules (translation/overwrite) from database."""
    try:
        query = """
            SELECT rule_type, source_column, target_column, source_value, target_value,
                   condition_column, condition_value, condition_operator
            FROM dbo.migration_translations
            WHERE active = 1
        """
        with misc_engine.begin() as con:
            translations_df = pd.read_sql(query, con)
        
        # Build list of rule dicts
        rules = []
        for _, row in translations_df.iterrows():
            rules.append({
                'rule_type': row.get('rule_type', 'translation'),
                'source_column': row.get('source_column'),
                'target_column': row.get('target_column'),
                'source_value': row.get('source_value'),
                'target_value': row.get('target_value'),
                'condition_column': row.get('condition_column'),
                'condition_value': row.get('condition_value'),
                'condition_operator': row.get('condition_operator') or 'contains'
            })
        return rules
    except Exception as e:
        print(f"[WARN] Failed to load translations: {e}")
        return []


def load_object_mappings(batch_id):
    """
    Load active object mappings for a specific batch from database.
    Returns a dict keyed by (source_dokob, source_objky) -> (target_dokob, target_objky)
    
    Args:
        batch_id: The batch ID to load mappings for
    """
    try:
        with misc_engine.begin() as con:
            result = con.execute(text("""
                SELECT source_dokob, source_objky, target_dokob, target_objky
                FROM dbo.migration_object_mapping
                WHERE batch_id = :batch_id AND active = 1
            """), {'batch_id': batch_id}).fetchall()
        
        if not result:
            print(f"[PREPARE] No object mappings configured for batch {batch_id}")
            return {}
        
        # Build lookup dict
        mappings = {}
        for row in result:
            key = (str(row[0]).upper(), str(row[1]))  # (source_dokob, source_objky)
            mappings[key] = (str(row[2]).upper(), str(row[3]))  # (target_dokob, target_objky)
        
        print(f"[PREPARE] Loaded {len(mappings)} object mappings for batch {batch_id}")
        return mappings
    except Exception as e:
        print(f"[WARN] Failed to load object mappings: {e}")
        return {}


def apply_object_mappings_for_batch(batch_id):
    """
    Apply object mappings to staging records for a specific batch.
    This should be called AFTER mappings have been uploaded for the batch.
    Updates target_dokob and target_objky in the staging table.
    
    Args:
        batch_id: The batch ID to apply mappings for
    """
    try:
        # Load mappings for this batch
        mappings = load_object_mappings(batch_id)
        
        if not mappings:
            print(f"[PREPARE] No mappings to apply for batch {batch_id}")
            return 0
        
        # Update staging records with target values
        updated = 0
        with misc_engine.begin() as con:
            for (source_dokob, source_objky), (target_dokob, target_objky) in mappings.items():
                result = con.execute(text("""
                    UPDATE dbo.migration_staging
                    SET target_dokob = :target_dokob, target_objky = :target_objky
                    WHERE batch_id = :batch_id 
                    AND source_dokob = :source_dokob 
                    AND source_objky = :source_objky
                """), {
                    'batch_id': batch_id,
                    'source_dokob': source_dokob,
                    'source_objky': source_objky,
                    'target_dokob': target_dokob,
                    'target_objky': target_objky
                })
                updated += result.rowcount
        
        print(f"[PREPARE] Applied mappings to {updated} staging records for batch {batch_id}")
        return updated
    except Exception as e:
        print(f"[WARN] Failed to apply object mappings: {e}")
        return 0


def enrich_loio_ids(data_df):
    """
    Enrich dataframe with LOIO_IDs from DIL.DMS_DOC2LOIO table.
    Uses document keys (documentnumber, documenttype, documentversion, documentpart) to lookup LOIO_IDs.
    
    This must be called BEFORE enrich_file_sizes() since file size lookup depends on LOIO_IDs.
    
    Returns dataframe with added 'loioid' column.
    """
    required_cols = ['documentnumber', 'documenttype', 'documentversion', 'documentpart']
    cols = [c.lower() for c in data_df.columns]
    
    if not all(k in cols for k in required_cols):
        print("[PREPARE] Missing document key columns for LOIO lookup")
        if 'loioid' not in data_df.columns:
            data_df['loioid'] = None
        return data_df
    
    if len(data_df) == 0:
        data_df['loioid'] = None
        return data_df
    
    print(f"[PREPARE] Looking up LOIO_IDs for {len(data_df)} documents...")
    
    try:
        # Build WHERE clause conditions for batch lookup
        conditions = []
        for _, row in data_df.iterrows():
            # Format values to match DIL table format
            doknr = str(row.get('documentnumber', '')).replace("'", "''")
            dokar = str(row.get('documenttype', '')).replace("'", "''")
            dokvr = str(row.get('documentversion', '')).replace("'", "''").zfill(2)  # Pad to 2 chars
            doktl = str(row.get('documentpart', '')).replace("'", "''").zfill(3)      # Pad to 3 chars
            conditions.append(
                f"(DOKNR='{doknr}' AND DOKAR='{dokar}' AND DOKVR='{dokvr}' AND DOKTL='{doktl}')"
            )
        
        # Query in chunks to avoid SQL statement size limits
        chunk_size = 200
        all_loios = []
        
        for i in range(0, len(conditions), chunk_size):
            chunk = conditions[i:i + chunk_size]
            where_clause = " OR ".join(chunk)
            query = f"""
                SELECT DOKNR, DOKAR, DOKVR, DOKTL, LO_OBJID
                FROM DIL.DMS_DOC2LOIO
                WHERE MANDT = '100'
                AND ({where_clause})
            """
            with dil_engine.begin() as con:
                chunk_df = pd.read_sql(query, con)
            all_loios.append(chunk_df)
        
        if all_loios:
            loio_df = pd.concat(all_loios, ignore_index=True)
            loio_df.columns = [c.lower() for c in loio_df.columns]
            
            # Prepare data_df columns for merge (ensure consistent formatting)
            data_df['_doknr'] = data_df['documentnumber'].astype(str)
            data_df['_dokar'] = data_df['documenttype'].astype(str)
            data_df['_dokvr'] = data_df['documentversion'].astype(str).str.zfill(2)
            data_df['_doktl'] = data_df['documentpart'].astype(str).str.zfill(3)
            
            # Merge to get LOIO_IDs
            data_df = data_df.merge(
                loio_df[['doknr', 'dokar', 'dokvr', 'doktl', 'lo_objid']],
                how='left',
                left_on=['_doknr', '_dokar', '_dokvr', '_doktl'],
                right_on=['doknr', 'dokar', 'dokvr', 'doktl']
            )
            data_df.rename(columns={'lo_objid': 'loioid'}, inplace=True)
            data_df.drop(columns=['_doknr', '_dokar', '_dokvr', '_doktl', 
                                  'doknr', 'dokar', 'dokvr', 'doktl'], errors='ignore', inplace=True)
            
            found_count = data_df['loioid'].notna().sum()
            print(f"[PREPARE] Found LOIO_IDs for {found_count}/{len(data_df)} documents")
        else:
            data_df['loioid'] = None
            
    except Exception as e:
        print(f"[WARN] Failed to enrich LOIO_IDs: {e}")
        if 'loioid' not in data_df.columns:
            data_df['loioid'] = None
    
    return data_df


def enrich_file_sizes(data_df):
    """
    Enrich dataframe with file sizes from DIL.DMS_FILE_SIZE table.
    Uses LOIO_ID to lookup file sizes.
    
    Returns dataframe with added 'file_size_bytes' column.
    """
    if 'loioid' not in data_df.columns or data_df['loioid'].isna().all():
        print("[PREPARE] No LOIO_IDs available for file size lookup")
        data_df['file_size_bytes'] = None
        return data_df
    
    # Collect unique LOIO_IDs
    loio_ids = data_df['loioid'].dropna().unique().tolist()
    if not loio_ids:
        data_df['file_size_bytes'] = None
        return data_df
    
    print(f"[PREPARE] Looking up file sizes for {len(loio_ids)} documents...")
    
    try:
        # Build query with IN clause (chunked for large batches)
        chunk_size = 500
        all_sizes = []
        
        for i in range(0, len(loio_ids), chunk_size):
            chunk = loio_ids[i:i + chunk_size]
            placeholders = ",".join([f"'{lid}'" for lid in chunk])
            query = f"""
                SELECT LOIO_ID, FILE_SIZE, FILE_NAME
                FROM DIL.DMS_FILE_SIZE
                WHERE LOIO_ID IN ({placeholders})
            """
            with dil_engine.begin() as con:
                chunk_df = pd.read_sql(query, con)
            all_sizes.append(chunk_df)
        
        if all_sizes:
            size_df = pd.concat(all_sizes, ignore_index=True)
            size_df.columns = [c.lower() for c in size_df.columns]
            
            # Merge with data
            data_df = data_df.merge(
                size_df[['loio_id', 'file_size']],
                how='left',
                left_on='loioid',
                right_on='loio_id'
            )
            data_df.rename(columns={'file_size': 'file_size_bytes'}, inplace=True)
            data_df.drop(columns=['loio_id'], errors='ignore', inplace=True)
            
            # Convert to int, handling NaN
            data_df['file_size_bytes'] = pd.to_numeric(data_df['file_size_bytes'], errors='coerce')
            
            # Log size distribution
            sizes = data_df['file_size_bytes'].dropna()
            if len(sizes) > 0:
                total_mb = sizes.sum() / (1024 * 1024)
                max_mb = sizes.max() / (1024 * 1024)
                over_50mb = (sizes > 50 * 1024 * 1024).sum()
                print(f"[PREPARE] File sizes: total={total_mb:.1f}MB, max={max_mb:.1f}MB, files>50MB={over_50mb}")
            else:
                print("[PREPARE] No file sizes found in DIL")
        else:
            data_df['file_size_bytes'] = None
            
    except Exception as e:
        print(f"[WARN] Failed to enrich file sizes: {e}")
        data_df['file_size_bytes'] = None
    
    return data_df


def enrich_descriptions_from_api(data_df, session_snapshot):
    """
    Enrich dataframe with document descriptions from Source API.
    Calls get_info() for each document and extracts DESCRIPTIONSSet / parent Description.
    
    Only fills rows where 'description' column is empty/NULL.
    Returns dataframe with 'description' column populated where API returned data.
    """
    if 'description' not in data_df.columns:
        data_df['description'] = None
    
    needs_desc = data_df['description'].isna() | (data_df['description'].astype(str).str.strip() == '') | (data_df['description'].astype(str) == 'None')
    if not needs_desc.any():
        print("[PREPARE] All rows already have descriptions, skipping API enrichment")
        return data_df
    
    cfg = Config.load()
    source_system = session_snapshot.get('source_system') or cfg.config_env.get('default_sap_system', 'zhl')
    
    print(f"[PREPARE] Enriching descriptions from {source_system} API for {needs_desc.sum()}/{len(data_df)} rows...")
    
    # Build API session
    server_session = requests.Session()
    try:
        prepare_session_headers(server_session, session_snapshot, source_system)
    except Exception as e:
        print(f"[WARN] Cannot prepare API session for description enrichment: {e}")
        return data_df
    
    filled = 0
    errors = 0
    for idx in data_df[needs_desc].index:
        row = data_df.loc[idx]
        doknr = str(row.get('documentnumber', '') or '')
        dokar = str(row.get('documenttype', '') or '')
        dokvr = str(row.get('documentversion', '') or '00')
        doktl = str(row.get('documentpart', '') or '000')
        
        if not doknr or not dokar:
            continue
        
        try:
            status_code, reason, files = get_info(
                server_session, source_system,
                doknr, doktl, dokar, dokvr
            )
            if status_code == 200 and files:
                first_file = files[0]
                # Priority: DocumentDescription (from DESCRIPTIONSSet/parent) > Description (file-level)
                desc = first_file.get('DocumentDescription') or first_file.get('Description')
                if desc and isinstance(desc, str) and desc.strip():
                    data_df.at[idx, 'description'] = desc.strip()
                    filled += 1
        except Exception as e:
            errors += 1
            if errors <= 3:
                print(f"[WARN] API description error for {doknr}: {e}")
            if errors == 3:
                print(f"[WARN] Suppressing further API description errors...")
        
        # Brief pause to avoid API throttling
        if filled % 50 == 0 and filled > 0:
            time.sleep(0.5)
    
    print(f"[PREPARE] API enriched {filled}/{needs_desc.sum()} descriptions ({errors} errors)")
    return data_df


def enrich_descriptions(data_df):
    """
    FALLBACK: Enrich dataframe with document descriptions from DIL.DRAT table.
    Only used for rows where API enrichment did not provide a description.
    DRAT contains the document short texts (DKTXT).
    Prefers English (LANGU='E'), falls back to any available language.
    
    Only fills rows where 'description' column is empty/NULL (does not overwrite existing values).
    
    Returns dataframe with 'description' column populated.
    """
    required_cols = ['documentnumber', 'documenttype', 'documentversion', 'documentpart']
    cols = [c.lower() for c in data_df.columns]
    
    if not all(k in cols for k in required_cols):
        print("[PREPARE] Missing document key columns for DRAT description lookup")
        return data_df
    
    if len(data_df) == 0:
        return data_df
    
    # Check how many rows already have a description
    if 'description' not in data_df.columns:
        data_df['description'] = None
    
    needs_desc = data_df['description'].isna() | (data_df['description'].astype(str).str.strip() == '') | (data_df['description'].astype(str) == 'None')
    if not needs_desc.any():
        print("[PREPARE] All rows already have descriptions, skipping DRAT lookup")
        return data_df
    
    print(f"[PREPARE] Looking up descriptions from DIL.DRAT for {needs_desc.sum()}/{len(data_df)} rows...")
    
    try:
        # Build WHERE clause conditions for batch lookup
        conditions = []
        for _, row in data_df[needs_desc].iterrows():
            doknr = str(row.get('documentnumber', '')).replace("'", "''")
            dokar = str(row.get('documenttype', '')).replace("'", "''")
            dokvr = str(row.get('documentversion', '')).replace("'", "''").zfill(2)
            doktl = str(row.get('documentpart', '')).replace("'", "''").zfill(3)
            conditions.append(
                f"(DOKNR='{doknr}' AND DOKAR='{dokar}' AND DOKVR='{dokvr}' AND DOKTL='{doktl}')"
            )
        
        # Query in chunks
        chunk_size = 200
        all_descs = []
        
        for i in range(0, len(conditions), chunk_size):
            chunk = conditions[i:i + chunk_size]
            where_clause = " OR ".join(chunk)
            query = f"""
                SELECT DOKNR, DOKAR, DOKVR, DOKTL, LANGU, DKTXT
                FROM DIL.DRAT
                WHERE MANDT = '100'
                AND ({where_clause})
            """
            with dil_engine.begin() as con:
                chunk_df = pd.read_sql(query, con)
            all_descs.append(chunk_df)
        
        if all_descs:
            desc_df = pd.concat(all_descs, ignore_index=True)
            desc_df.columns = [c.lower() for c in desc_df.columns]
            
            if len(desc_df) > 0:
                # Prefer English descriptions, fall back to any language
                desc_en = desc_df[desc_df['langu'] == 'E'].drop_duplicates(
                    subset=['doknr', 'dokar', 'dokvr', 'doktl'], keep='first'
                )
                desc_any = desc_df.drop_duplicates(
                    subset=['doknr', 'dokar', 'dokvr', 'doktl'], keep='first'
                )
                # Use English where available, fall back to any
                desc_final = desc_en if len(desc_en) > 0 else desc_any
                if len(desc_en) > 0 and len(desc_en) < len(desc_any.drop_duplicates(subset=['doknr', 'dokar', 'dokvr', 'doktl'])):
                    # Merge: English first, then fill gaps from any language
                    desc_final = desc_en.merge(
                        desc_any[['doknr', 'dokar', 'dokvr', 'doktl', 'dktxt']],
                        on=['doknr', 'dokar', 'dokvr', 'doktl'],
                        how='right',
                        suffixes=('_en', '_any')
                    )
                    desc_final['dktxt'] = desc_final.get('dktxt_en', desc_final.get('dktxt'))
                    if 'dktxt_any' in desc_final.columns:
                        desc_final['dktxt'] = desc_final['dktxt'].fillna(desc_final['dktxt_any'])
                    desc_final = desc_final.drop_duplicates(subset=['doknr', 'dokar', 'dokvr', 'doktl'], keep='first')
                
                # Merge descriptions into data_df
                data_df['_doknr'] = data_df['documentnumber'].astype(str)
                data_df['_dokar'] = data_df['documenttype'].astype(str)
                data_df['_dokvr'] = data_df['documentversion'].astype(str).str.zfill(2)
                data_df['_doktl'] = data_df['documentpart'].astype(str).str.zfill(3)
                
                data_df = data_df.merge(
                    desc_final[['doknr', 'dokar', 'dokvr', 'doktl', 'dktxt']],
                    how='left',
                    left_on=['_doknr', '_dokar', '_dokvr', '_doktl'],
                    right_on=['doknr', 'dokar', 'dokvr', 'doktl']
                )
                
                # Fill missing descriptions from DRAT
                drat_filled = data_df['dktxt'].notna() & needs_desc
                data_df.loc[drat_filled, 'description'] = data_df.loc[drat_filled, 'dktxt']
                
                filled_count = drat_filled.sum()
                print(f"[PREPARE] Enriched {filled_count}/{needs_desc.sum()} descriptions from DIL.DRAT")
                
                # Cleanup merge columns
                data_df.drop(columns=['_doknr', '_dokar', '_dokvr', '_doktl',
                                      'doknr', 'dokar', 'dokvr', 'doktl', 'dktxt', 'langu',
                                      'dktxt_en', 'dktxt_any'],
                             errors='ignore', inplace=True)
            else:
                print("[PREPARE] No descriptions found in DIL.DRAT")
        else:
            print("[PREPARE] No DRAT query results")
            
    except Exception as e:
        print(f"[WARN] Failed to enrich descriptions from DRAT: {e}")
    
    return data_df


def apply_translations(data_df, rules):
    """Apply migration rules: translation mappings and overwrites with optional conditions."""
    if not rules or len(data_df) == 0:
        return data_df

    for rule in rules:
        rtype = (rule.get('rule_type') or 'translation').lower()
        source_col = rule.get('source_column')
        target_col = rule.get('target_column')
        source_val = rule.get('source_value')
        target_val = rule.get('target_value')
        cond_col = rule.get('condition_column')
        cond_val = rule.get('condition_value')
        cond_op = (rule.get('condition_operator') or 'contains').lower()

        # Skip rules missing core target info (allow empty string, but not None)
        if not target_col or target_val is None:
            continue

        # Ensure target column exists (default to current value or None)
        if target_col not in data_df.columns:
            data_df[target_col] = None

        # Build mask based on condition
        mask = pd.Series([True] * len(data_df))
        if cond_col and cond_col in data_df.columns and cond_val is not None:
            col_series = data_df[cond_col].astype(str)
            if cond_op == 'contains':
                mask = col_series.str.contains(str(cond_val), case=False, na=False)
            elif cond_op == 'not_contains':
                mask = ~col_series.str.contains(str(cond_val), case=False, na=False)
            elif cond_op == 'equals':
                mask = col_series == str(cond_val)
            elif cond_op == 'not_equal':
                mask = col_series != str(cond_val)
            else:
                # Fallback: exact match
                mask = col_series == str(cond_val)
        elif source_col and source_col in data_df.columns and source_val is not None:
            # Legacy translation condition: source_column contains/matches source_value
            col_series = data_df[source_col].astype(str)
            mask = col_series.str.contains(str(source_val), case=False, na=False)

        if rtype == 'translation':
            # Translation: when mask true, set target to target_val, else keep existing or source value
            # If target column not yet populated, default to source column for unmatched rows
            if source_col and source_col in data_df.columns:
                # Only copy from source if target is still None/empty (preserve prior rule results)
                needs_default = data_df[target_col].isna() | (data_df[target_col] == '')
                data_df.loc[~mask & needs_default, target_col] = data_df.loc[~mask & needs_default, source_col]
            # Convert empty string to None/NULL for proper clearing
            final_val = None if target_val == '' else target_val
            data_df.loc[mask, target_col] = final_val
            print(f"[RULE] Applied translation rule to {mask.sum()} rows ({source_col} -> {target_col})")
        elif rtype == 'overwrite':
            # Overwrite: set fixed value in target column for rows matching mask
            # Convert empty string to None/NULL for proper clearing
            final_val = None if target_val == '' else target_val
            data_df.loc[mask, target_col] = final_val
            print(f"[RULE] Applied overwrite rule to {mask.sum()} rows (set {target_col} = {final_val}))")

    return data_df


def generate_batch_id():
    """Generate unique batch ID for tracking."""
    return f"BATCH_{dt.datetime.now(dt.timezone.utc).strftime('%Y%m%d_%H%M%S')}_{uuid.uuid4().hex[:8]}"


def load_source_data(source_file_path=None, custom_query=None, query_source='dil'):
    """Load source document data from Excel or database query."""
    if source_file_path:
        # Load from Excel file
        data_df = pd.read_excel(source_file_path)
        # Normalize column names to lowercase for consistency
        data_df.columns = [str(c).strip().lower() for c in data_df.columns]
    else:
        # Load from database query
        if not custom_query:
            raise ValueError("No SQL query provided. Please provide a query to load data from the database.")
        
        # Select engine based on query source
        engine = dil_engine if query_source == 'dil' else misc_engine
        
        if engine is None:
            raise ValueError(f"Database engine for '{query_source}' is not available. Check database configuration.")
        
        with engine.begin() as con:
            data_df = pd.read_sql(custom_query, con)
        # Already aliased to lowercase; ensure consistent formatting
        data_df.columns = [str(c).strip().lower() for c in data_df.columns]
    
    # Apply zfill rules
    zfill_rules = {
        "documentnumber": 25,
        "documentpart": 3,
        "documentversion": 2,
    }
    for col, width in zfill_rules.items():
        if col in data_df.columns:
            data_df[col] = data_df[col].apply(
                lambda x: str(x).zfill(width) if pd.notnull(x) and str(x).isnumeric() else x
            )
    
    return data_df


def enrich_with_metadata(data_df, session_snapshot=None):
    """Enrich source data with authorization groups and computed target fields.
    
    Args:
        data_df: DataFrame with source document data
        session_snapshot: Optional dict with bearer_token etc. for API enrichment.
                          If provided, descriptions are fetched from API first, DRAT as fallback.
    """
    # Fetch authorization groups in batch
    if len(data_df) == 0:
        return data_df
    
    # Ensure expected columns exist (Excel may have different casing)
    cols = set(data_df.columns)
    
    # Check if Excel already has authorization_group column with values
    excel_has_auth_group = 'authorization_group' in cols
    excel_auth_filled = False
    if excel_has_auth_group:
        # Check if any values are non-empty (not NaN, not empty string)
        excel_auth_filled = data_df['authorization_group'].notna().any() and \
                            (data_df['authorization_group'].astype(str).str.strip() != '').any()
    
    # NOTE: Authorization Group (BEGRU) is now fetched from API Authoritygroup during Execute phase
    # No DIL.DRAW query needed here - just initialize empty column if not provided in Excel
    if not excel_auth_filled:
        data_df['authorization_group'] = None
    # else: Keep Excel authorization_group values as-is
    
    # Store source authorization group BEFORE rule application (for UI display)
    data_df['source_authorization_group'] = data_df['authorization_group'].copy()
    
    # Apply translation rules
    translation_map = load_translations()
    if translation_map:
        data_df = apply_translations(data_df, translation_map)
    
    # Preserve source_dokob/source_objky from Excel/SQL if present, otherwise init empty
    if 'source_dokob' not in data_df.columns:
        data_df['source_dokob'] = None
    if 'source_objky' not in data_df.columns:
        data_df['source_objky'] = None
    
    # Initialize target DOKOB/OBJKY columns (will be filled when mappings are uploaded for this batch)
    if 'target_dokob' not in data_df.columns:
        data_df['target_dokob'] = None
    if 'target_objky' not in data_df.columns:
        data_df['target_objky'] = None
    
    # Document status: initialize if not already provided (from Excel or SQL query)
    if 'source_document_status' not in data_df.columns:
        data_df['source_document_status'] = None
    if 'target_document_status' not in data_df.columns:
        data_df['target_document_status'] = None
    
    # Enrich with LOIO_IDs from DIL.DMS_DOC2LOIO (required for file size lookup)
    data_df = enrich_loio_ids(data_df)
    
    # Enrich with file sizes from DIL.DMS_FILE_SIZE
    data_df = enrich_file_sizes(data_df)
    
    # Enrich descriptions: API first (if session available), DRAT as fallback
    if session_snapshot and session_snapshot.get('bearer_token'):
        data_df = enrich_descriptions_from_api(data_df, session_snapshot)
    
    # DRAT fallback for any remaining rows without description
    data_df = enrich_descriptions(data_df)
    
    # NOTE: Filenames are now extracted from API Docpath during Execute phase
    # No DIL.DRAW query needed here - the API provides full path with extension
    data_df['source_filename'] = None
    
    # Compute target document numbers based on target document type
    # Rules (apply_translations above) may have already changed target_documenttype,
    # so we use the effective target type to decide:
    # - IY1/IY2 with purely numeric DOKNR → None (S4 auto-generates)
    # - IY1/IY2 with alphanumeric DOKNR → preserve (manual override)
    # - Other types: preserve source document number
    INTERNAL_NUMBERING_TYPES = {'IY1', 'IY2'}
    
    def _is_purely_numeric(val):
        """Check if value is purely numeric (digits only)."""
        return bool(val) and str(val).strip().isdigit()
    
    def compute_target_docnumber(row):
        """Determine target document number based on target type and source number."""
        # If rules already set target_documentnumber, keep it
        existing = row.get('target_documentnumber')
        if pd.notnull(existing) and str(existing).strip():
            return str(existing).strip()[:25]
        
        # Check target document type (may have been mapped by rules)
        target_type = str(row.get('target_documenttype', '') or '').strip().upper()
        
        # Get source document number
        dn = row.get('documentnumber') if 'documentnumber' in row.index else None
        source_nr = str(dn)[:25] if pd.notnull(dn) else None
        
        if target_type in INTERNAL_NUMBERING_TYPES:
            # Internal numbering types: only preserve alphanumeric values
            # Purely numeric → None (S4 auto-generates)
            # Alphanumeric → preserve (manual override)
            if source_nr and not _is_purely_numeric(source_nr):
                # Pre-check: would sanitization leave anything useful?
                sanitized_check, _ = sanitize_doknr(source_nr)
                if not sanitized_check or not sanitized_check.strip():
                    return None  # Sanitization empties this value → treat as auto-generate
                return source_nr
            return None
        
        # Non-internal-numbering type: always preserve source document number
        return source_nr

    # Ensure target_documentnumber column exists
    if 'target_documentnumber' not in data_df.columns:
        data_df['target_documentnumber'] = None
    
    # Apply compute logic row-by-row (needs access to target_documenttype)
    if 'documentnumber' in data_df.columns or 'target_documenttype' in data_df.columns:
        data_df['target_documentnumber'] = data_df.apply(compute_target_docnumber, axis=1)
    
    internal_mask = data_df['target_documenttype'].astype(str).str.strip().str.upper().isin(INTERNAL_NUMBERING_TYPES)
    internal_null = (internal_mask & data_df['target_documentnumber'].isna()).sum()
    internal_kept = (internal_mask & data_df['target_documentnumber'].notna()).sum()
    print(f"[PREPARE] target_documentnumber: {data_df['target_documentnumber'].notna().sum()} set, "
          f"{internal_null} null (numeric→auto-generate), {internal_kept} kept (alphanumeric→manual)")
    
    # Compute sanitized document numbers (fix slashes, umlauts, OData-unsafe chars)
    def _sanitize_target_docnumber(val):
        if pd.isna(val) or not str(val).strip():
            return None
        sanitized, _changed = sanitize_doknr(str(val))
        if not sanitized or not sanitized.strip():
            return None  # Sanitization emptied the value
        return sanitized
    
    data_df['target_documentnumber_sanitized'] = data_df['target_documentnumber'].apply(_sanitize_target_docnumber)
    changed_count = ((data_df['target_documentnumber'].notna()) & 
                     (data_df['target_documentnumber_sanitized'] != data_df['target_documentnumber'])).sum()
    print(f"[PREPARE] target_documentnumber_sanitized: {changed_count} values changed by sanitization")
    
    # Clean up any duplicate columns (can occur from multiple merges)
    if data_df.columns.duplicated().any():
        # Keep only first occurrence of each column
        data_df = data_df.loc[:, ~data_df.columns.duplicated()]
        print(f"[PREPARE] Removed duplicate columns")
    
    return data_df


def prepare_staging_records(data_df, batch_id, source_file_name=None):
    """Transform source data into staging records format.
    
    Deduplicates by (documentnumber, documentpart, documentversion) so that
    each unique source document produces exactly ONE staging record.
    Multiple DOKOB/OBJKY entries for the same document are collected into
    a JSON array in source_object_links.
    """
    import json
    
    current_user = http_session.get('user_email', 'system')
    
    # --- Deduplication: collect all DOKOB/OBJKY pairs per unique document ---
    doc_key_cols = ['documentnumber', 'documentpart', 'documentversion']
    
    # Build a composite key for grouping (handles NaN gracefully)
    def _doc_key(row):
        return (
            str(row.get('documentnumber', '') or ''),
            str(row.get('documentpart', '000') or '000'),
            str(row.get('documentversion', '00') or '00'),
        )
    
    # Collect all object links per unique document
    object_links_map = {}  # doc_key -> list of unique (dokob, objky) tuples
    for _, row in data_df.iterrows():
        key = _doc_key(row)
        dokob = row.get('source_dokob')
        objky = row.get('source_objky')
        if key not in object_links_map:
            object_links_map[key] = []
        if pd.notnull(dokob) and pd.notnull(objky):
            pair = (str(dokob).strip(), str(objky).strip())
            if pair not in object_links_map[key]:  # Deduplicate (dokob, objky) pairs
                object_links_map[key].append(pair)
    
    # Deduplicate DataFrame: keep first occurrence of each document
    before_count = len(data_df)
    data_df = data_df.drop_duplicates(subset=[c for c in doc_key_cols if c in data_df.columns], keep='first')
    dedup_count = before_count - len(data_df)
    if dedup_count > 0:
        print(f"[PREPARE] Deduplicated: {before_count} → {len(data_df)} records ({dedup_count} duplicate rows removed)")
    
    # --- Build staging records ---
    staging_records = []
    
    for _, row in data_df.iterrows():
        key = _doc_key(row)
        links = object_links_map.get(key, [])
        
        # First DOKOB/OBJKY goes into the primary columns (backward compatible)
        first_dokob = links[0][0] if links else (str(row.get('source_dokob', '') or '').strip() or None)
        first_objky = links[0][1] if links else (str(row.get('source_objky', '') or '').strip() or None)
        
        # All links as JSON array
        links_json = json.dumps([{'dokob': d, 'objky': o} for d, o in links]) if links else None
        
        record = {
            'batch_id': batch_id,
            'created_by': current_user,
            'source_documentnumber': row.get('documentnumber'),
            'source_documentpart': row.get('documentpart', '000'),
            'source_documenttype': row.get('documenttype', 'IY1'),
            'source_documentversion': row.get('documentversion', '00'),
            'source_loioid': row.get('loioid'),
            'source_description': row.get('description') or row.get('documentdescription'),
            'source_dokob': first_dokob,
            'source_objky': first_objky,
            'source_object_links': links_json,
            'target_documentnumber': row.get('target_documentnumber'),
            'target_documentnumber_sanitized': row.get('target_documentnumber_sanitized'),
            'target_documentpart': row.get('documentpart', '000'),
            'target_documenttype': row.get('documenttype', 'IY1'),
            'target_documentversion': row.get('documentversion', '00'),
            'target_dokob': row.get('target_dokob'),
            'target_objky': row.get('target_objky'),
            'source_document_status': row.get('source_document_status'),
            'target_document_status': row.get('target_document_status'),
            'source_authorization_group': row.get('source_authorization_group'),
            'authorization_group': row.get('authorization_group'),
            'filename': row.get('source_filename'),  # From DIL.DRAW.filep (with extension)
            'file_size_bytes': row.get('file_size_bytes'),
            'ablage': row.get('ablage', 'KPRO'),
            'validation_status': 'pending',
            'execution_status': 'pending',
            'user_approved': 0,
            'skip_migration': 0
        }
        staging_records.append(record)
    
    # Log object link stats
    multi_link_count = sum(1 for links in object_links_map.values() if len(links) > 1)
    if multi_link_count > 0:
        print(f"[PREPARE] {multi_link_count} documents have multiple object links (stored in source_object_links)")
    
    return pd.DataFrame(staging_records)


def save_to_staging(staging_df, batch_id, source_file_name=None, wave=None, description=None, notes=None):
    """Save prepared records to staging database."""
    current_user = http_session.get('user_email', 'system')
    
    # Save staging records in chunks (SQL Server limit: 1000 rows per INSERT)
    chunk_size = 900  # Stay safely under 1000 limit
    total_rows = len(staging_df)
    
    with misc_engine.begin() as con:
        # Insert in chunks to avoid SQL Server 1000 row limit
        for i in range(0, total_rows, chunk_size):
            chunk_df = staging_df.iloc[i:i + chunk_size]
            chunk_df.to_sql(
                'migration_staging',
                con,
                schema='dbo',
                if_exists='append',
                index=False,
                method='multi'
            )
            print(f"[PREPARE] Inserted rows {i+1}-{min(i+chunk_size, total_rows)} of {total_rows}")
        
        # Create batch record
        batch_record = pd.DataFrame([{
            'batch_id': batch_id,
            'created_by': current_user,
            'source_file': source_file_name or 'database_query',
            'total_records': len(staging_df),
            'status': 'prepared',
            'wave': wave,
            'description': description,
            'notes': notes
        }])
        
        batch_record.to_sql(
            'migration_batch',
            con,
            schema='dbo',
            if_exists='append',
            index=False
        )
    
    print(f"[PREPARE] Saved {len(staging_df)} records to staging with batch_id={batch_id}")
    return batch_id


def prepare_migration(source_file_path=None, custom_query=None, query_source='dil', wave=None, description=None, notes=None, session_snapshot=None):
    """
    Main entry point for Step 1: Data Preparation
    
    Args:
        session_snapshot: Optional dict with bearer_token etc. for API-based enrichment.
    
    Returns:
        dict with batch_id, record_count, and status
    """
    try:
        # Generate batch ID
        batch_id = generate_batch_id()
        
        # Load source data
        print(f"[PREPARE] Loading source data...")
        data_df = load_source_data(source_file_path, custom_query=custom_query, query_source=query_source)
        print(f"[PREPARE] Loaded {len(data_df)} records")
        
        if len(data_df) == 0:
            return {
                'success': False,
                'error': 'No records found in source data'
            }
        
        # Enrich with metadata
        print(f"[PREPARE] Enriching with metadata...")
        data_df = enrich_with_metadata(data_df, session_snapshot=session_snapshot)
        
        # Prepare staging records
        print(f"[PREPARE] Preparing staging records...")
        staging_df = prepare_staging_records(data_df, batch_id, source_file_path)
        
        # Save to database
        print(f"[PREPARE] Saving to staging database...")
        batch_id = save_to_staging(staging_df, batch_id, source_file_path, wave=wave, description=description, notes=notes)
        
        return {
            'success': True,
            'batch_id': batch_id,
            'record_count': len(staging_df),
            'status': 'prepared'
        }
        
    except Exception as e:
        print(f"[PREPARE_ERROR] {e}")
        import traceback
        traceback.print_exc()
        return {
            'success': False,
            'error': str(e)
        }
