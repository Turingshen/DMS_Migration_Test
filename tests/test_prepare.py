class TestApplyTranslations:
    """Tests for apply_translations() function."""
    
    def test_translation_rule(self):
        from app.prepare import apply_translations
        
        df = pd.DataFrame([
            {'documenttype': 'IY1', 'description': 'Test'},
            {'documenttype': 'IY2', 'description': 'Other'},
        ])
        
        rules = [{
            'rule_type': 'translation',
            'source_column': 'documenttype',
            'target_column': 'target_documenttype',
            'source_value': 'IY1',
            'target_value': 'DRW',
            'condition_column': None,
            'condition_value': None,
            'condition_operator': None
        }]
        
        result = apply_translations(df, rules)
        
        assert result.loc[0, 'target_documenttype'] == 'DRW'
        # IY2 should not be translated
        assert result.loc[1, 'target_documenttype'] != 'DRW'
    
    def test_overwrite_rule(self):
        from app.prepare import apply_translations
        
        df = pd.DataFrame([
            {'documenttype': 'IY1', 'authorization_group': None},
            {'documenttype': 'IY2', 'authorization_group': 'EXISTING'},
        ])
        
        rules = [{
            'rule_type': 'overwrite',
            'source_column': None,
            'target_column': 'authorization_group',
            'source_value': None,
            'target_value': 'DEFAULT_AUTH',
            'condition_column': 'documenttype',
            'condition_value': 'IY1',
            'condition_operator': 'equals'
        }]
        
        result = apply_translations(df, rules)
        
        assert result.loc[0, 'authorization_group'] == 'DEFAULT_AUTH'
        # IY2 should keep existing value
        assert result.loc[1, 'authorization_group'] == 'EXISTING'
    
    def test_empty_rules(self):
        from app.prepare import apply_translations
        
        df = pd.DataFrame([{'documenttype': 'IY1'}])
        result = apply_translations(df, [])
        
        assert len(result) == 1
        assert result.loc[0, 'documenttype'] == 'IY1'
    
    def test_empty_dataframe(self):
        from app.prepare import apply_translations
        
        df = pd.DataFrame()
        rules = [{'rule_type': 'translation', 'target_column': 'x', 'target_value': 'y'}]
        result = apply_translations(df, rules)
        
        assert len(result) == 0


class TestGenerateBatchId:
    """Tests for generate_batch_id() function."""
    
    def test_format(self):
        from app.prepare import generate_batch_id
        batch_id = generate_batch_id()
        
        # Should start with BATCH_
        assert batch_id.startswith("BATCH_")
        
        # Should contain date/time pattern
        parts = batch_id.split("_")
        assert len(parts) >= 3
        
        # Date part should be 8 digits
        assert len(parts[1]) == 8
        assert parts[1].isdigit()
    
    def test_uniqueness(self):
        from app.prepare import generate_batch_id
        import time
        
        id1 = generate_batch_id()
        time.sleep(0.01)  # Small delay to ensure different timestamp
        id2 = generate_batch_id()
        
        assert id1 != id2


