class TestDynamicPacing:
    """Tests for get_dynamic_pacing() function."""
    
    def test_tiny_file(self):
        """Files <= 1MB should get 5s pacing."""
        from app.execute import get_dynamic_pacing
        assert get_dynamic_pacing(500 * 1024) == 5  # 500KB
    
    def test_small_file(self):
        """Files 1-10MB should get 10s pacing."""
        from app.execute import get_dynamic_pacing
        assert get_dynamic_pacing(5 * 1024 * 1024) == 10  # 5MB
    
    def test_medium_file(self):
        """Files 10-50MB should get 20s pacing."""
        from app.execute import get_dynamic_pacing
        assert get_dynamic_pacing(25 * 1024 * 1024) == 20  # 25MB
    
    def test_large_file(self):
        """Files > 50MB should get 45s pacing."""
        from app.execute import get_dynamic_pacing
        assert get_dynamic_pacing(100 * 1024 * 1024) == 45  # 100MB
    
    def test_none_size(self):
        """None size should use tiny pacing as default."""
        from app.execute import get_dynamic_pacing
        assert get_dynamic_pacing(None) == 5
    
    def test_zero_size(self):
        """Zero size should use tiny pacing."""
        from app.execute import get_dynamic_pacing
        assert get_dynamic_pacing(0) == 5
    
    def test_negative_size(self):
        """Negative size (invalid) should use tiny pacing."""
        from app.execute import get_dynamic_pacing
        assert get_dynamic_pacing(-100) == 5
